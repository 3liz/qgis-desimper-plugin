BEGIN;

-- Flow arrows and flow lines computed on the project polygon
-- with hydro.fleches_ecoulement() and hydro.lignes_ecoulement().
-- They are computed together with the automatic watershed,
-- and removed when the project geometry changes.

-- Flow arrows: one point per mesh, with the mean flow direction
CREATE TABLE desimper.fleches_ecoulement (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fk_id_projet integer NOT NULL REFERENCES desimper.projets(id) ON DELETE CASCADE,
    angle double precision NOT NULL,
    coherence double precision,
    nb_cellules integer,
    geom geometry(Point, 2154) NOT NULL,
    cree_le timestamp without time zone DEFAULT (now())::timestamp(0) without time zone
);

CREATE INDEX fleches_ecoulement_geom_idx ON desimper.fleches_ecoulement USING gist (geom);
CREATE INDEX fleches_ecoulement_fk_id_projet_idx ON desimper.fleches_ecoulement USING btree (fk_id_projet);

COMMENT ON TABLE desimper.fleches_ecoulement IS 'Flèches d''écoulement des projets : une flèche par maille, orientée selon la direction moyenne de l''écoulement D8 des cellules de la maille. Calculées avec hydro.fleches_ecoulement().';

COMMENT ON COLUMN desimper.fleches_ecoulement.id IS 'Identifiant unique de la flèche.';
COMMENT ON COLUMN desimper.fleches_ecoulement.fk_id_projet IS 'Projet associé à la flèche.';
COMMENT ON COLUMN desimper.fleches_ecoulement.angle IS 'Direction de l''écoulement, en degrés depuis le nord dans le sens des aiguilles d''une montre (rotation des symboles QGIS).';
COMMENT ON COLUMN desimper.fleches_ecoulement.coherence IS 'Cohérence des directions de la maille, de 0 (replat, crête) à 1 (toutes les cellules vont dans le même sens).';
COMMENT ON COLUMN desimper.fleches_ecoulement.nb_cellules IS 'Nombre de cellules du MNT prises en compte dans la maille.';
COMMENT ON COLUMN desimper.fleches_ecoulement.geom IS 'Centre de la maille.';
COMMENT ON COLUMN desimper.fleches_ecoulement.cree_le IS 'Date de calcul de la flèche.';

-- Flow lines: traced from cell to cell from regularly spaced starting points
CREATE TABLE desimper.lignes_ecoulement (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fk_id_projet integer NOT NULL REFERENCES desimper.projets(id) ON DELETE CASCADE,
    depart bigint,
    longueur double precision,
    geom geometry(LineString, 2154) NOT NULL,
    cree_le timestamp without time zone DEFAULT (now())::timestamp(0) without time zone
);

CREATE INDEX lignes_ecoulement_geom_idx ON desimper.lignes_ecoulement USING gist (geom);
CREATE INDEX lignes_ecoulement_fk_id_projet_idx ON desimper.lignes_ecoulement USING btree (fk_id_projet);

COMMENT ON TABLE desimper.lignes_ecoulement IS 'Lignes d''écoulement des projets : tracées de cellule en cellule selon les directions D8, depuis des points de départ régulièrement espacés, et prolongées au-delà du projet. Calculées avec hydro.lignes_ecoulement().';

COMMENT ON COLUMN desimper.lignes_ecoulement.id IS 'Identifiant unique de la ligne.';
COMMENT ON COLUMN desimper.lignes_ecoulement.fk_id_projet IS 'Projet associé à la ligne.';
COMMENT ON COLUMN desimper.lignes_ecoulement.depart IS 'Identifiant de la cellule de départ de la ligne dans la grille hydrologique.';
COMMENT ON COLUMN desimper.lignes_ecoulement.longueur IS 'Longueur de la ligne (m).';
COMMENT ON COLUMN desimper.lignes_ecoulement.geom IS 'Tracé de la ligne d''écoulement.';
COMMENT ON COLUMN desimper.lignes_ecoulement.cree_le IS 'Date de calcul de la ligne.';


-- Compute (or recompute) the flow arrows and lines of a project
CREATE OR REPLACE FUNCTION desimper.calculer_ecoulements(
    id_projet integer,
    pas_fleches double precision DEFAULT 5,
    espacement_lignes double precision DEFAULT 10,
    marge_lignes double precision DEFAULT 50
) RETURNS json
    LANGUAGE plpgsql
    AS $$
DECLARE
    projet_geom geometry;
    nb_fleches integer;
    nb_lignes integer;
BEGIN

    -- The hydro functions are installed apart from this plugin
    IF to_regprocedure('hydro.fleches_ecoulement(geometry,double precision)') IS NULL
        OR to_regprocedure('hydro.lignes_ecoulement(geometry,double precision,double precision)') IS NULL
    THEN
        RAISE EXCEPTION 'Les fonctions hydro.fleches_ecoulement(geometry, double precision) et hydro.lignes_ecoulement(geometry, double precision, double precision) sont absentes de la base : impossible de calculer les écoulements.';
    END IF;

    SELECT p.geom INTO projet_geom
    FROM desimper.projets AS p
    WHERE p.id = id_projet;

    IF projet_geom IS NULL THEN
        RAISE EXCEPTION 'Le projet % n''existe pas.', id_projet;
    END IF;

    -- Replace the previous computation
    DELETE FROM desimper.fleches_ecoulement AS f
    WHERE f.fk_id_projet = id_projet;

    DELETE FROM desimper.lignes_ecoulement AS l
    WHERE l.fk_id_projet = id_projet;

    -- Flow arrows
    INSERT INTO desimper.fleches_ecoulement (fk_id_projet, angle, coherence, nb_cellules, geom)
    SELECT id_projet, f.angle, f.coherence, f.nb_cellules, ST_Transform(f.geom, 2154)
    FROM hydro.fleches_ecoulement(projet_geom, pas_fleches) AS f
    WHERE f.geom IS NOT NULL
    AND f.angle IS NOT NULL;

    GET DIAGNOSTICS nb_fleches = ROW_COUNT;

    -- Flow lines
    INSERT INTO desimper.lignes_ecoulement (fk_id_projet, depart, longueur, geom)
    SELECT id_projet, l.depart, l.longueur, ST_Transform(l.geom, 2154)
    FROM hydro.lignes_ecoulement(projet_geom, espacement_lignes, marge_lignes) AS l
    WHERE GeometryType(l.geom) = 'LINESTRING';

    GET DIAGNOSTICS nb_lignes = ROW_COUNT;

    RETURN json_build_object(
        'fk_id_projet', id_projet,
        'nb_fleches', nb_fleches,
        'nb_lignes', nb_lignes
    );
END;
$$;

COMMENT ON FUNCTION desimper.calculer_ecoulements(id_projet integer, pas_fleches double precision, espacement_lignes double precision, marge_lignes double precision) IS 'Calcule (ou recalcule) les flèches et les lignes d''écoulement d''un projet avec hydro.fleches_ecoulement() et hydro.lignes_ecoulement(), et les enregistre dans fleches_ecoulement et lignes_ecoulement.
Paramètres : taille des mailles des flèches (m), espacement des départs des lignes (m), prolongement des lignes au-delà du projet (m).
Renvoie le nombre de flèches et de lignes enregistrées.';


-- Remove the flow arrows and lines when the project geometry changes
CREATE OR REPLACE FUNCTION desimper.trg_after_projet_insert_or_update() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN

    -- Do nothing if the geometry has not changed
    IF TG_OP = 'INSERT' OR NOT ST_Equals(NEW.geom, OLD.geom) THEN
        -- Fill the contextes_projets table
        PERFORM desimper.fill_contextes_projets(NEW.id);

        IF TG_OP = 'UPDATE' THEN
            -- The automatic watershed is not valid anymore
            -- The corrected one is kept
            DELETE FROM desimper.bassins_versants
            WHERE fk_id_projet = NEW.id
            AND NOT corrige;

            -- The flow arrows and lines are not valid anymore
            DELETE FROM desimper.fleches_ecoulement
            WHERE fk_id_projet = NEW.id;

            DELETE FROM desimper.lignes_ecoulement
            WHERE fk_id_projet = NEW.id;
        END IF;

        -- TO DO
        -- Check if surface are fitting in the new project geom...

    END IF;

    RETURN NEW;

END;
$$;

COMMENT ON FUNCTION desimper.trg_after_projet_insert_or_update() IS 'Fonction trigger permettant de mettre à jour les tables de données métier en lien avec le projet.
Appelle desimper.fill_contextes_projets() avec l''identifiant du projet.
Supprime le bassin versant automatique du projet (le bassin versant corrigé est conservé), ainsi que ses flèches et lignes d''écoulement.
Ne fait rien si la géométrie du projet n''a pas changé.';

COMMIT;
