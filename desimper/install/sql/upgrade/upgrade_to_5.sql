-- Add new table to manage watersheds ("bassins versants")
-- Each project has at most 2 watersheds:
--   * the one computed automatically (corrige = false)
--   * the one corrected by the user (corrige = true)
CREATE TABLE desimper.bassins_versants (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fk_id_projet integer NOT NULL REFERENCES desimper.projets(id) ON DELETE CASCADE,
    corrige boolean NOT NULL DEFAULT false,
    geom geometry(MultiPolygon, 2154) NOT NULL,
    cree_le timestamp without time zone DEFAULT (now())::timestamp(0) without time zone,
    modifie_le timestamp without time zone DEFAULT (now())::timestamp(0) without time zone,
    login text,
    CONSTRAINT bassins_versants_fk_id_projet_corrige_key UNIQUE (fk_id_projet, corrige)
);

CREATE INDEX bassins_versants_geom_idx ON desimper.bassins_versants USING gist (geom);

COMMENT ON TABLE desimper.bassins_versants IS 'Table pour stocker les bassins versants associés aux projets. Au plus 2 bassins versants par projet : celui calculé automatiquement (corrige = false) et celui corrigé par l''utilisateur (corrige = true).';

COMMENT ON COLUMN desimper.bassins_versants.id IS 'Identifiant unique du bassin versant.';
COMMENT ON COLUMN desimper.bassins_versants.fk_id_projet IS 'Projet associé au bassin versant.';
COMMENT ON COLUMN desimper.bassins_versants.corrige IS 'Indique si le bassin versant a été corrigé par l''utilisateur.';
COMMENT ON COLUMN desimper.bassins_versants.geom IS 'Géométrie du bassin versant.';
COMMENT ON COLUMN desimper.bassins_versants.cree_le IS 'Date de création du bassin versant.';
COMMENT ON COLUMN desimper.bassins_versants.modifie_le IS 'Date de dernière modification du bassin versant.';
COMMENT ON COLUMN desimper.bassins_versants.login IS 'Login de l''utilisateur ayant modifié le bassin versant.';

-- Manage cree_le, modifie_le and geom precision
CREATE TRIGGER trg_aa_before_insert_or_update
    BEFORE INSERT OR UPDATE ON desimper.bassins_versants
    FOR EACH ROW EXECUTE PROCEDURE desimper.aa_before_insert_or_update();


-- Compute the automatic watershed of a project
CREATE OR REPLACE FUNCTION desimper.calculer_bassin_versant(id_projet integer) RETURNS json
    LANGUAGE plpgsql
    AS $$
DECLARE
    projet_geom geometry;
    bv_geom geometry;
    bv_id integer;
BEGIN

    -- The hydro functions are installed apart from this plugin
    IF to_regprocedure('hydro.bassin_polygone(geometry,double precision)') IS NULL THEN
        RAISE EXCEPTION 'La fonction hydro.bassin_polygone(geometry, double precision) est absente de la base : impossible de calculer le bassin versant.';
    END IF;

    SELECT p.geom INTO projet_geom
    FROM desimper.projets AS p
    WHERE p.id = id_projet;

    IF projet_geom IS NULL THEN
        RAISE EXCEPTION 'Le projet % n''existe pas.', id_projet;
    END IF;

    -- Watershed of the project polygon (project included), simplified at 1 m
    bv_geom = ST_Multi(ST_CollectionExtract(hydro.bassin_polygone(projet_geom, 1), 3));

    IF bv_geom IS NULL OR ST_IsEmpty(bv_geom) THEN
        RAISE EXCEPTION 'Le bassin versant du projet % n''a pas pu être calculé (projet hors des données hydrologiques ?).', id_projet;
    END IF;

    INSERT INTO desimper.bassins_versants (fk_id_projet, corrige, geom)
    VALUES (id_projet, false, bv_geom)
    ON CONFLICT (fk_id_projet, corrige)
    DO UPDATE SET geom = EXCLUDED.geom
    RETURNING id INTO bv_id;

    RETURN json_build_object(
        'type', 'FeatureCollection',
        'features', json_build_array(
            json_build_object(
                'type', 'Feature',
                'id', bv_id,
                'geometry', ST_AsGeoJSON(bv_geom)::json,
                'properties', json_build_object(
                    'id', bv_id,
                    'fk_id_projet', id_projet,
                    'corrige', false
                )
            )
        )
    );
END;
$$;

COMMENT ON FUNCTION desimper.calculer_bassin_versant(id_projet integer) IS 'Calcule (ou recalcule) le bassin versant automatique d''un projet avec hydro.bassin_polygone() et l''enregistre dans bassins_versants avec corrige = false.
Le bassin versant corrigé par l''utilisateur n''est pas modifié.
Renvoie le bassin versant en GeoJSON (FeatureCollection).';


-- Create the corrected watershed of a project from the automatic one
CREATE OR REPLACE FUNCTION desimper.creer_bassin_versant_corrige(id_projet integer) RETURNS integer
    LANGUAGE plpgsql
    AS $$
DECLARE
    bv_id integer;
BEGIN

    -- The corrected watershed already exists
    SELECT bv.id INTO bv_id
    FROM desimper.bassins_versants AS bv
    WHERE bv.fk_id_projet = id_projet
    AND bv.corrige;

    IF bv_id IS NOT NULL THEN
        RETURN bv_id;
    END IF;

    -- Copy the automatic watershed
    INSERT INTO desimper.bassins_versants (fk_id_projet, corrige, geom)
    SELECT bv.fk_id_projet, true, bv.geom
    FROM desimper.bassins_versants AS bv
    WHERE bv.fk_id_projet = id_projet
    AND NOT bv.corrige
    RETURNING id INTO bv_id;

    IF bv_id IS NULL THEN
        RAISE EXCEPTION 'Le projet % n''a pas de bassin versant calculé automatiquement à corriger.', id_projet;
    END IF;

    RETURN bv_id;
END;
$$;

COMMENT ON FUNCTION desimper.creer_bassin_versant_corrige(id_projet integer) IS 'Crée le bassin versant corrigé (corrige = true) d''un projet en copiant son bassin versant automatique.
Ne fait rien s''il existe déjà.
Renvoie l''identifiant du bassin versant corrigé.';


-- Remove the automatic watershed when the project geometry changes
CREATE OR REPLACE FUNCTION desimper.trg_after_projet_insert_or_update() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN

    -- Do nothing if the geometry has not changed
    IF TG_OP = 'INSERT' OR NOT ST_Equals(NEW.geom, OLD.geom) THEN
        -- Fill the contextes_projets table
        PERFORM desimper.fill_contextes_projets(NEW.id);

        -- The automatic watershed is not valid anymore
        -- The corrected one is kept
        IF TG_OP = 'UPDATE' THEN
            DELETE FROM desimper.bassins_versants
            WHERE fk_id_projet = NEW.id
            AND NOT corrige;
        END IF;

        -- TO DO
        -- Check if surface are fitting in the new project geom...

    END IF;

    RETURN NEW;

END;
$$;

COMMENT ON FUNCTION desimper.trg_after_projet_insert_or_update() IS 'Fonction trigger permettant de mettre à jour les tables de données métier en lien avec le projet.
Appelle desimper.fill_contextes_projets() avec l''identifiant du projet.
Supprime le bassin versant automatique du projet (le bassin versant corrigé est conservé).
Ne fait rien si la géométrie du projet n''a pas changé.';

